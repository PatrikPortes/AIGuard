#!/usr/bin/env python3
"""Reproducible delivery encodings of approved PNGs; original files stay untouched.
Needs Pillow with WebP support in development only. No crop/drawing/generation.
"""
from pathlib import Path
from PIL import Image
import hashlib, json, math

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / 'public'
DEST = PUBLIC / 'assets/characters/optimized'
DEST.mkdir(exist_ok=True)
sources = [*(f'verka/verka-{s}.png' for s in ['welcome','thinking','explaining','warning','success']),
           *(f'robo/robo-{s}.png' for s in ['default','analyzing','searching','warning','success','tip','capacity','error']), 'verkarob.png']
sha = lambda b: hashlib.sha256(b).hexdigest()
assets, records = {}, []
cream = (255, 250, 244, 255)
for source in sources:
    path = PUBLIC / 'assets/characters' / source
    original_bytes = path.read_bytes()
    original = Image.open(path).convert('RGBA')
    reference = original.copy()
    reference.thumbnail((840,840) if source == 'verkarob.png' else (384,384), Image.Resampling.LANCZOS)
    # Full canvas and aspect preserved; all resampled RGBA pixels are lossless.
    temp = DEST / (path.stem + '.encoding.tmp')
    reference.save(temp, format='WEBP', lossless=True, quality=100, method=6, exact=True)
    encoded = temp.read_bytes(); digest = sha(encoded)
    target = DEST / f'{path.stem}.{digest}.webp'
    if target.exists(): assert target.read_bytes() == encoded
    else: target.write_bytes(encoded)
    temp.unlink()
    decoded = Image.open(target).convert('RGBA')
    assert decoded.size == reference.size
    assert decoded.getchannel('A').tobytes() == reference.getchannel('A').tobytes()
    # Compare perceptual delivery error on the actual cream background, not
    # hidden RGB under alpha=0. Resampling is independently represented above.
    def composite(img):
        return Image.alpha_composite(Image.new('RGBA', img.size, cream), img).convert('RGB').tobytes()
    a,b = composite(reference),composite(decoded)
    mse = sum((x-y)**2 for x,y in zip(a,b)) / len(a)
    psnr = round(10*math.log10(255**2/mse),3) if mse else 100.0
    assert decoded.tobytes() == reference.tobytes(), source
    assert path.read_bytes() == original_bytes
    url = '/' + target.relative_to(PUBLIC).as_posix()
    assets[path.stem] = url
    records.append({'name':path.stem,'url':url,'width':decoded.width,'height':decoded.height,'bytes':len(encoded),
                    'sha256':digest,'source':'assets/characters/'+source,'source_sha256':sha(original_bytes),
                    'source_bytes':len(original_bytes),'source_width':original.width,'source_height':original.height,
                    'alpha_range':decoded.getchannel('A').getextrema(),'alpha_equal_to_resampled_source':True,
                    'webp_lossless':True,'cream_composite_psnr_db':psnr})
module = '// Generated by scripts/optimize-characters.py from approved, unchanged PNGs.\n'
module += 'export const characterAssets = '+json.dumps(assets,ensure_ascii=False,indent=2)+';\n'
module += 'export const characterAssetFiles = '+json.dumps(records,ensure_ascii=False,indent=2)+';\n'
(PUBLIC/'character-assets.js').write_text(module)
print(json.dumps({'assets':len(records),'source_bytes':sum(r['source_bytes'] for r in records),
                  'delivery_bytes':sum(r['bytes'] for r in records),'minimum_psnr_db':min(r['cream_composite_psnr_db'] for r in records)},indent=2))
